class _TopkolikLocalizationsDelegate extends LocalizationsDelegate<TopkolikLocalizations> {
  const _TopkolikLocalizationsDelegate();

  @override
  bool isSupported(Locale locale) {
    return ['de', 'fr', 'it', 'en', 'tr'].contains(locale.languageCode);
  }

  @override
  Future<TopkolikLocalizations> load(Locale locale) {
    final effectiveLocale = isSupported(locale) ? locale : const Locale('en');
    return SynchronousFuture<TopkolikLocalizations>(TopkolikLocalizations(effectiveLocale));
  }

  @override
  bool shouldReload(_TopkolikLocalizationsDelegate old) => false;
}
